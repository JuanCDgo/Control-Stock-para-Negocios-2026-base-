-- ---------- comercios ----------
-- La app solo lee id + nombre_negocio (database.init_db). El resto de la config
-- del negocio vive en config_negocio.json, no en la base.
create table if not exists public.comercios (
    id             bigint generated by default as identity primary key,
    nombre_negocio text        not null,
    created_at     timestamptz not null default now()
);

-- ---------- categorias ----------
create table if not exists public.categorias (
    id          bigint generated by default as identity primary key,
    comercio_id bigint not null references public.comercios(id),
    nombre      text   not null,
    -- importar_productos_masivo espera que un insert duplicado falle y re-busca por nombre
    constraint categorias_nombre_unico unique (comercio_id, nombre)
);

-- ---------- productos ----------
create table if not exists public.productos (
    id                bigint generated by default as identity primary key,
    comercio_id       bigint         not null references public.comercios(id),
    codigo            text           not null,                 -- código de barras / SKU
    nombre            text           not null,
    categoria_id      bigint         references public.categorias(id),  -- nullable: import puede dejarla null
    precio_costo      numeric(12,2)  not null default 0,
    margen_ganancia   numeric(8,2)   not null default 0,       -- porcentaje
    precio_venta      numeric(12,2)  not null default 0,
    usa_precio_manual boolean        not null default false,
    stock_actual      numeric(12,3)  not null default 0,
    stock_minimo      numeric(12,3)  not null default 0,
    imagen_url        text           default '',               -- URL pública del bucket 'productos' o ruta local
    created_at        timestamptz    not null default now(),   -- inferido (no lo lee la app)
    constraint productos_codigo_unico unique (comercio_id, codigo)
);

-- ---------- clientes ----------
create table if not exists public.clientes (
    id             bigint generated by default as identity primary key,
    comercio_id    bigint        not null references public.comercios(id),
    nombre         text          not null,
    telefono       text          default '',
    email          text          default '',
    limite_credito numeric(12,2) not null default 0,           -- 0 = sin límite (RPC)
    saldo_deudor   numeric(12,2) not null default 0,
    created_at     timestamptz   not null default now()
);

-- ---------- ventas (cabecera / ticket) ----------
create table if not exists public.ventas (
    id          bigint generated by default as identity primary key,
    comercio_id bigint        not null references public.comercios(id),
    cliente_id  bigint        references public.clientes(id),  -- sin cascade: eliminar_cliente espera 23503
    total_venta numeric(12,2) not null default 0,
    forma_pago  text          not null default 'Efectivo',     -- 'Efectivo', 'Cuenta Corriente...', etc.
    fecha_hora  timestamptz   not null default now()           -- la RPC no la setea: depende del default
);

-- ---------- detalle_ventas (renglones) ----------
-- Sin comercio_id a propósito: la RPC no lo inserta, el restore no lo setea y el reset
-- filtra por venta_id.
create table if not exists public.detalle_ventas (
    id              bigint generated by default as identity primary key,
    venta_id        bigint        not null references public.ventas(id),
    producto_id     bigint        references public.productos(id),  -- sin cascade: eliminar_producto espera 23503
    cantidad        numeric(12,3) not null,
    precio_unitario numeric(12,2) not null default 0,
    costo_unitario  numeric(12,2) not null default 0
);

-- ---------- movimientos_cuenta (cuenta corriente / "libreta") ----------
create table if not exists public.movimientos_cuenta (
    id          bigint generated by default as identity primary key,
    comercio_id bigint        not null references public.comercios(id),
    cliente_id  bigint        not null references public.clientes(id),
    tipo        text          not null,                        -- 'CARGO' | 'PAGO'
    monto       numeric(12,2) not null,
    descripcion text,
    ticket_id   bigint        references public.ventas(id),    -- solo en CARGO (venta fiada)
    fecha_hora  timestamptz   not null default now()
);

-- ---------- Índices para los filtros habituales ----------
create index if not exists productos_comercio_idx          on public.productos (comercio_id, nombre);
create index if not exists clientes_comercio_idx           on public.clientes (comercio_id, nombre);
create index if not exists ventas_comercio_fecha_idx       on public.ventas (comercio_id, fecha_hora desc);
create index if not exists detalle_ventas_venta_idx        on public.detalle_ventas (venta_id);
create index if not exists detalle_ventas_producto_idx     on public.detalle_ventas (producto_id);
create index if not exists movimientos_cuenta_cliente_idx  on public.movimientos_cuenta (comercio_id, cliente_id);

-- ---------- Comercio inicial ----------
-- usuarios_auth.sql crea los usuarios del comercio 1 y database.init_db lo lee.
insert into public.comercios (id, nombre_negocio)
overriding system value
values (1, 'Comercio 001')
on conflict (id) do nothing;
select setval(pg_get_serial_sequence('public.comercios', 'id'), (select max(id) from public.comercios));

-- =====================================================================
-- Storage: bucket 'productos' (fotos de productos, app.py guardar_archivo_imagen)
-- La app sube / borra con la anon key y muestra la URL pública -> bucket público
-- + políticas en storage.objects (upload = insert; remove = select + delete).
-- =====================================================================
insert into storage.buckets (id, name, public)
values ('productos', 'productos', true)
on conflict (id) do update set public = true;

drop policy if exists "productos_bucket_select" on storage.objects;
drop policy if exists "productos_bucket_insert" on storage.objects;
drop policy if exists "productos_bucket_update" on storage.objects;
drop policy if exists "productos_bucket_delete" on storage.objects;
create policy "productos_bucket_select" on storage.objects for select
    to anon, authenticated using (bucket_id = 'productos');
create policy "productos_bucket_insert" on storage.objects for insert
    to anon, authenticated with check (bucket_id = 'productos');
create policy "productos_bucket_update" on storage.objects for update
    to anon, authenticated using (bucket_id = 'productos');
create policy "productos_bucket_delete" on storage.objects for delete
    to anon, authenticated using (bucket_id = 'productos');

